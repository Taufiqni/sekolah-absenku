-- SEKOLAH ABSENKU: skema awal database
-- Jalankan di Supabase SQL Editor pada proyek yang benar.
-- RLS sengaja diaktifkan. Policy rinci harus dibuat dan diuji sebelum dipakai sungguhan.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role text not null check (role in ('siswa','guru','admin','orang_tua')),
  created_at timestamptz not null default now()
);
create table if not exists public.classes (
  id bigint generated by default as identity primary key,
  name text not null unique,
  homeroom_teacher_id uuid references public.profiles(id)
);
create table if not exists public.students (
  id bigint generated by default as identity primary key,
  user_id uuid unique references public.profiles(id),
  class_id bigint references public.classes(id),
  qr_token uuid not null unique default gen_random_uuid(),
  created_at timestamptz not null default now()
);
create table if not exists public.parent_students (
  parent_id uuid not null references public.profiles(id) on delete cascade,
  student_id bigint not null references public.students(id) on delete cascade,
  primary key (parent_id, student_id)
);
create table if not exists public.attendance (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(id),
  attendance_date date not null default current_date,
  check_in timestamptz,
  check_out timestamptz,
  status text not null default 'hadir' check (status in ('hadir','izin','sakit','alpha')),
  recorded_by uuid references public.profiles(id),
  created_at timestamptz not null default now(),
  unique (student_id, attendance_date)
);
create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  parent_id uuid not null references public.profiles(id) on delete cascade,
  student_id bigint not null references public.students(id) on delete cascade,
  message text not null,
  created_at timestamptz not null default now(),
  read_at timestamptz
);
alter table public.profiles enable row level security;
alter table public.classes enable row level security;
alter table public.students enable row level security;
alter table public.parent_students enable row level security;
alter table public.attendance enable row level security;
alter table public.notifications enable row level security;

